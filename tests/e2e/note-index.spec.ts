import { expect, test, type Page, type APIRequestContext } from "./fixtures";
import type { ConversationDetail, SideNote } from "../../src/lib/types";
import { docsImage } from "../fixtures/docs-image";

async function setup(page: Page, request: APIRequestContext) {
  const conversation = await (await request.post("/api/conversations", { data: { providerKind: "mock", model: "mock-demo" } })).json();
  await request.post("/api/chat/main", { data: { ownerId: conversation.id, text: "MCPの付箋を一覧で振り返る" } });
  await page.goto(`/?chat=${conversation.id}`);
  for (const text of ["Tool", "Resource", "Prompt"]) {
    const word = page.locator("[data-message-id] strong").filter({ hasText: new RegExp(`^${text}$`) }).first();
    await word.evaluate((element) => {
      const range = document.createRange(); range.selectNodeContents(element);
      const selection = window.getSelection()!; selection.removeAllRanges(); selection.addRange(range);
      element.dispatchEvent(new MouseEvent("mouseup", { bubbles: true }));
    });
    await page.getByRole("button", { name: "付箋", exact: true }).click();
    await expect(page.getByTestId("floating-note").filter({ has: page.locator(".note-title", { hasText: text }) })).toBeVisible();
  }
  const read = async (): Promise<ConversationDetail> => (await request.get(`/api/conversations/${conversation.id}`)).json();
  const notes = (await read()).notes;
  const tool = notes.find((n) => n.selectedText === "Tool")!, resource = notes.find((n) => n.selectedText === "Resource")!, prompt = notes.find((n) => n.selectedText === "Prompt")!;
  await request.patch(`/api/notes/${tool.id}`, { data: { memo: "検索APIを呼び出すための道具" } });
  await request.patch(`/api/notes/${tool.id}/layout`, { data: { x: 760, y: 80, width: 320, height: 300, collapsed: true } });
  await request.patch(`/api/notes/${resource.id}`, { data: { memo: "後から確認する共有データ", color: "blue" } });
  await request.patch(`/api/notes/${resource.id}/layout`, { data: { x: 760, y: 1300, width: 320, height: 350, minimized: true, connector: { source: { side: "right", ratio: 0.5, segment: 0 }, target: { side: "top", ratio: 0.2 }, bend: { x: 10, y: -40 } } } });
  await request.patch(`/api/notes/${prompt.id}`, { data: { color: "pink" } });
  await request.post("/api/chat/note", { data: { ownerId: prompt.id, text: "一覧から探す合言葉について説明して" } });
  await request.patch(`/api/notes/${prompt.id}/layout`, { data: { x: 70, y: 700, width: 320, height: 360 } });
  await page.reload();
  return { id: conversation.id as string, tool, resource, prompt, read };
}

const panel = (page: Page) => page.getByRole("dialog", { name: /^この会話の付箋/ });
const row = (page: Page, note: SideNote) => panel(page).locator(`[data-testid="note-index-item"][data-note-id="${note.id}"]`);
const floating = (page: Page, note: SideNote) => page.locator(`[data-testid="floating-note"][data-note-id="${note.id}"]`);

test("lists this conversation's notes, searches their contents, and reveals stored or collapsed notes without changing content", async ({ page, request }) => {
  const { resource, tool, prompt, read } = await setup(page, request);
  const before = (await read()).notes.find((n) => n.id === resource.id)!;
  await floating(page, prompt).getByLabel("付箋で追加質問").fill("まだ送っていない確認事項");
  const index = page.getByRole("button", { name: "付箋一覧を開く", exact: true });
  await expect(index).toContainText("3");
  await index.click();
  await expect(panel(page).getByTestId("note-index-item")).toHaveCount(3);
  await expect(panel(page).getByLabel("付箋を検索", { exact: true })).toBeFocused();
  await expect(row(page, resource)).toHaveAttribute("data-note-color", "blue");
  await expect(row(page, resource)).toContainText("マーカーに収納");
  await expect(row(page, resource)).toContainText("後から確認する共有データ");
  await expect(row(page, tool)).toContainText("折りたたみ中");
  await expect(row(page, prompt)).toContainText("AIとの会話");
  await page.screenshot({ path: docsImage("note-index.png") });
  const search = panel(page).getByLabel("付箋を検索", { exact: true });
  await search.fill("ｒｅｓｏｕｒｃｅ");
  // Also finds Resource in the Prompt note's AI reply.
  await expect(panel(page).getByTestId("note-index-item")).toHaveCount(2);
  await expect(row(page, resource)).toBeVisible();
  await expect(row(page, prompt)).toBeVisible();
  await search.fill("共有 データ");
  await expect(panel(page).getByTestId("note-index-item")).toHaveCount(1);
  await expect(row(page, resource)).toBeVisible();
  await search.fill("合言葉");
  await expect(row(page, prompt)).toBeVisible();
  await expect(panel(page).getByTestId("note-index-item")).toHaveCount(1);
  await search.fill("存在しない検索語");
  await expect(panel(page)).toContainText("該当する付箋がありません");
  await panel(page).getByRole("button", { name: "すべての付箋を表示", exact: true }).click();
  await panel(page).getByRole("button", { name: /^しまった付箋/ }).click();
  await expect(panel(page).getByTestId("note-index-item")).toHaveCount(1);
  await row(page, resource).click();
  await expect(panel(page)).toHaveCount(0);
  await expect(floating(page, resource)).toBeFocused();
  await expect(floating(page, resource)).toBeInViewport({ ratio: 0.8 });
  expect(await page.locator(".canvas-scroll").evaluate((el) => el.scrollTop)).toBeGreaterThan(700);
  await expect(floating(page, resource).getByLabel("付箋のメモ")).toHaveValue(before.memo);
  await expect(floating(page, prompt).getByLabel("付箋で追加質問")).toHaveValue("まだ送っていない確認事項");
  const restored = (await read()).notes.find((n) => n.id === resource.id)!;
  expect(restored.layout).toMatchObject({ ...before.layout, minimized: false, collapsed: false, zIndex: expect.any(Number), updatedAt: expect.any(Number) });
  expect({ ...restored, layout: before.layout }).toEqual(before);
  await index.click();
  await expect(row(page, resource)).toContainText("表示中");
  await row(page, tool).click();
  await expect(floating(page, tool)).toBeFocused();
  await expect(floating(page, tool).getByLabel("付箋のメモ")).toHaveValue("検索APIを呼び出すための道具");
  await expect(floating(page, tool)).toBeInViewport();
  await floating(page, tool).getByLabel("付箋のメモ").fill("一覧にも反映される最新メモ");
  await index.click();
  await expect(row(page, tool)).toContainText("一覧にも反映される最新メモ");
  await page.keyboard.press("Escape");
  await expect(index).toBeFocused();
  await expect(panel(page)).toHaveCount(0);
  await expect.poll(async () => (await read()).notes.find((n) => n.id === tool.id)?.memo).toBe("一覧にも反映される最新メモ");
  await page.reload();
  await index.click();
  await expect(panel(page).getByTestId("note-index-item")).toHaveCount(3);
  await expect(row(page, resource)).toContainText("表示中");
  await expect(row(page, tool)).toContainText("一覧にも反映される最新メモ");
  await row(page, tool).click();
  page.once("dialog", (dialog) => dialog.accept());
  await floating(page, tool).getByRole("button", { name: "付箋を削除", exact: true }).click();
  await expect(floating(page, tool)).toHaveCount(0);
  await index.click();
  await expect(panel(page).getByTestId("note-index-item")).toHaveCount(2);
  await expect(row(page, tool)).toHaveCount(0);
});

test("keeps failed restores in the list for retry and isolates empty and different conversations", async ({ page, request }) => {
  const { id, resource } = await setup(page, request);
  const empty = await (await request.post("/api/conversations", { data: { providerKind: "mock", model: "mock-demo" } })).json();
  await request.patch(`/api/conversations/${empty.id}`, { data: { title: "付箋ゼロの会話" } });
  await page.reload();
  const index = page.getByRole("button", { name: "付箋一覧を開く", exact: true });
  await index.click();
  await page.route(`**/api/notes/${resource.id}/layout`, (route) => route.fulfill({ status: 500, json: { error: "保存失敗のテスト" } }));
  await row(page, resource).click();
  await expect(panel(page).getByRole("alert")).toContainText("もう一度選んでください");
  await expect(row(page, resource)).toContainText("マーカーに収納");
  await expect(floating(page, resource)).toHaveCount(0);
  await page.unroute(`**/api/notes/${resource.id}/layout`);
  await row(page, resource).focus(); await page.keyboard.press("Enter");
  await expect(panel(page)).toHaveCount(0);
  await expect(floating(page, resource)).toBeFocused();
  await index.click();
  await panel(page).getByRole("button", { name: "付箋一覧を閉じる", exact: true }).click();
  await expect(index).toBeFocused();
  await page.locator(`[data-conversation-id="${empty.id}"] .conversation-link`).click();
  await expect(page).toHaveURL(new RegExp(empty.id));
  await index.click();
  await expect(panel(page).getByTestId("note-index-item")).toHaveCount(0);
  await expect(panel(page)).toContainText("この会話には、まだ付箋がありません");
  await expect(panel(page)).toContainText("＋付箋");
  await page.mouse.click(500, 100);
  await expect(panel(page)).toHaveCount(0);
  await page.locator(`[data-conversation-id="${id}"] .conversation-link`).click();
  await expect(page).toHaveURL(new RegExp(id));
  await index.click();
  await expect(panel(page).getByTestId("note-index-item")).toHaveCount(3);
  await panel(page).getByLabel("付箋を検索", { exact: true }).fill("前の検索を残さない");
  await page.keyboard.press("Escape");
  await page.locator(".new-chat").click();
  await index.click();
  await expect(panel(page).getByLabel("付箋を検索", { exact: true })).toHaveValue("");
  await expect(panel(page).getByTestId("note-index-item")).toHaveCount(0);
});
